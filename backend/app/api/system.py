class SelectModelsRequest(BaseModel):
    llm_model: str = Field(..., min_length=1, description="Selected text generation LLM")
    embed_model: Optional[str] = Field(None, min_length=1, description="Selected dense embedding model")

class ConfigUpdateRequest(BaseModel):
    chunk_size: int = Field(..., ge=100, le=4000, description="Max tokens per document chunk")
    chunk_overlap: int = Field(..., ge=0, le=1000, description="Overlap tokens between adjacent chunks")
    retrieval_top_k: int = Field(..., ge=1, le=20, description="Number of top chunks retrieved by RAG")
    model_output_limit: int = Field(..., ge=64, le=4096, description="Max output tokens generated by local LLM")
    temperature: Optional[float] = Field(None, ge=0.0, le=1.0, description="LLM sampling temperature")

    @model_validator(mode="after")
    def validate_chunk_overlap(self):
        if self.chunk_overlap >= self.chunk_size:
            raise ValueError(
                f"Chunk overlap ({self.chunk_overlap}) must be strictly less than chunk size ({self.chunk_size})."
            )
        return self

class ConfigResponse(BaseModel):
    chunk_size: int
    chunk_overlap: int
    retrieval_top_k: int
    model_output_limit: int
    temperature: float
    context_length: int
    timeout_seconds: float
    is_low_ram_optimized: bool

class AgentLogItem(BaseModel):
    id: str
    project_id: Optional[str]
    agent_name: str
    action_type: str
    input_payload: Optional[str]
    output_summary: Optional[str]
    status: str
    duration_ms: Optional[int]
    error_message: Optional[str]
    created_at: Optional[str]

class AgentLogsResponse(BaseModel):
    total_count: int
    logs: List[AgentLogItem]

