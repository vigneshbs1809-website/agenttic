@router.post("/config", response_model=ConfigResponse)
def update_system_configuration(payload: ConfigUpdateRequest):
    """
    Validates and updates runtime system configuration.
    Ensures chunk overlap is strictly less than chunk size and values are within safe boundaries.
    """
    settings.MAX_CHUNK_TOKENS = payload.chunk_size
    settings.CHUNK_OVERLAP_TOKENS = payload.chunk_overlap
    settings.TOP_K_RETRIEVAL = payload.retrieval_top_k
    settings.LLM_MAX_OUTPUT_TOKENS = payload.model_output_limit
    ollama_service.max_output_tokens = payload.model_output_limit

    if payload.temperature is not None:
        settings.LLM_TEMPERATURE = payload.temperature
        ollama_service.temperature = payload.temperature

    return ConfigResponse(
        chunk_size=settings.MAX_CHUNK_TOKENS,
        chunk_overlap=settings.CHUNK_OVERLAP_TOKENS,
        retrieval_top_k=settings.TOP_K_RETRIEVAL,
        model_output_limit=settings.LLM_MAX_OUTPUT_TOKENS,
        temperature=settings.LLM_TEMPERATURE,
        context_length=settings.LLM_CONTEXT_LENGTH,
        timeout_seconds=settings.OLLAMA_TIMEOUT_SECONDS,
        is_low_ram_optimized=True,
    )

@router.get("/agent-logs", response_model=AgentLogsResponse)
def get_agent_execution_logs(
    agent_name: Optional[str] = Query(None, description="Filter by agent name"),
    status: Optional[str] = Query(None, description="Filter by status (completed, failed)"),
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
    db: Session = Depends(get_db)
):
    """
    Retrieves real agent execution logs stored in SQLite (agent_execution_histories).
    """
    q = db.query(AgentExecutionHistory)

    if isinstance(agent_name, str) and agent_name.strip():
        q = q.filter(AgentExecutionHistory.agent_name == agent_name.strip())
    if isinstance(status, str) and status.strip():
        q = q.filter(AgentExecutionHistory.status == status.strip())

    safe_limit = limit if isinstance(limit, int) else 50
    safe_offset = offset if isinstance(offset, int) else 0

    total = q.count()
    records = q.order_by(desc(AgentExecutionHistory.created_at)).offset(safe_offset).limit(safe_limit).all()

    logs = []
    for r in records:
        logs.append(AgentLogItem(
            id=r.id,
            project_id=r.project_id,
            agent_name=r.agent_name,
            action_type=r.action_type,
            input_payload=r.input_payload,
            output_summary=r.output_summary,
            status=r.status,
            duration_ms=r.duration_ms,
            error_message=r.error_message,
            created_at=r.created_at.isoformat() if r.created_at else None,
        ))

    return AgentLogsResponse(
        total_count=total,
        logs=logs
    )
