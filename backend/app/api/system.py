@router.get("/status")
def get_complete_system_status(db: Session = Depends(get_db)):
    """
    Returns actual, un-fabricated status across all 8 platform subsystems:
    1. Ollama connection & installed models
    2. Selected LLM parameters
    3. Embedding model status
    4. SQLite database metrics (WAL mode, size, row counts)
    5. ChromaDB vector collections & chunks
    6. PDF document storage telemetry
    7. Backend API metadata
    8. Hardware memory & Windows 11 8GB RAM envelope
    """
    # 1. Hardware RAM Telemetry
    mem = psutil.virtual_memory()
    ram_used_mb = round(mem.used / (1024 * 1024), 2)
    ram_total_mb = round(mem.total / (1024 * 1024), 2)
    ram_percent = mem.percent

    # 2. SQLite Database Telemetry
    db_file = get_db_file_path()
    db_size_mb = round(db_file.stat().st_size / (1024 * 1024), 2) if db_file.exists() else 0.0

    try:
        with engine.connect() as conn:
            sqlite_ver = conn.execute(text("SELECT sqlite_version();")).scalar()
            journal_mode = conn.execute(text("PRAGMA journal_mode;")).scalar()
            sync_mode = conn.execute(text("PRAGMA synchronous;")).scalar()
        db_connected = True
        db_error = None
    except Exception as e:
        sqlite_ver = "Unknown"
        journal_mode = "Unknown"
        sync_mode = "Unknown"
        db_connected = False
        db_error = str(e)

    total_projects = db.query(ResearchProject).count()
    total_papers = db.query(ResearchPaper).count()
    total_sections = db.query(PaperSection).count()
    total_gaps = db.query(ResearchGap).count()
    total_verifications = db.query(VerificationResult).count()
    total_contradictions = db.query(ResearchContradiction).count()
    total_agent_logs = db.query(AgentExecutionHistory).count()

    # 3. ChromaDB Telemetry
    chroma_dir = Path(settings.CHROMA_PERSIST_DIR)
    chroma_size_mb = round(_calculate_dir_size_bytes(chroma_dir) / (1024 * 1024), 2)
    try:
        cs = ChromaService()
        chroma_connected = True
        chroma_collection = cs.collection_name
        chroma_chunks = cs.collection.count()
        collections_list = [c.name for c in cs.client.list_collections()]
        chroma_error = None
    except Exception as e:
        chroma_connected = False
        chroma_collection = "literature_chunks"
        chroma_chunks = 0
        collections_list = []
        chroma_error = str(e)

    # 4. PDF Storage Telemetry
    pdf_dir = Path(settings.PDF_STORAGE_DIR)
    pdf_exists = pdf_dir.exists()
    pdf_files = [f for f in os.listdir(pdf_dir) if f.lower().endswith(".pdf")] if pdf_exists else []
    pdf_size_mb = round(_calculate_dir_size_bytes(pdf_dir) / (1024 * 1024), 2)

    # 5. Live Ollama Telemetry
    ollama_data = ollama_service.get_connection_status_sync()
    installed_models = ollama_service.get_installed_models_sync() if ollama_data.get("connected") else []

    return {
        "timestamp": time.time(),
        "backend": {
            "name": settings.APP_NAME,
            "version": settings.APP_VERSION,
            "environment": settings.ENVIRONMENT,
            "host": settings.HOST,
            "port": settings.PORT,
            "status": "healthy" if db_connected else "degraded",
            "uptime_seconds": round(time.time() - psutil.Process().create_time(), 1),
            "pid": os.getpid()
        },
        "system_resources": {
            "ram_used_mb": ram_used_mb,
            "ram_total_mb": ram_total_mb,
            "ram_percent": ram_percent,
            "is_low_ram_environment": ram_total_mb <= 8500,
            "platform": "Windows 11 (64-bit)"
        },
        "sqlite": {
            "connected": db_connected,
            "error": db_error,
            "path": str(db_file),
            "size_mb": db_size_mb,
            "version": sqlite_ver,
            "journal_mode": journal_mode,
            "synchronous": sync_mode,
            "counts": {
                "projects": total_projects,
                "papers": total_papers,
                "sections": total_sections,
                "gaps": total_gaps,
                "verifications": total_verifications,
                "contradictions": total_contradictions,
                "agent_logs": total_agent_logs,
            }
        },
        "chromadb": {
            "connected": chroma_connected,
            "error": chroma_error,
            "persist_dir": str(chroma_dir),
            "size_mb": chroma_size_mb,
            "active_collection": chroma_collection,
            "total_chunks_indexed": chroma_chunks,
            "collections": collections_list,
            "distance_metric": "cosine (HNSW)"
        },
        "pdf_storage": {
            "dir_path": str(pdf_dir),
            "exists": pdf_exists,
            "total_pdf_files": len(pdf_files),
            "total_size_mb": pdf_size_mb,
            "writable": os.access(pdf_dir, os.W_OK) if pdf_exists else False
        },
        "ollama": {
            "connected": ollama_data.get("connected", False),
            "base_url": settings.OLLAMA_BASE_URL,
            "error": ollama_data.get("error"),
            "installed_models_count": len(installed_models),
            "installed_models": installed_models,
        },
        "selected_llm": {
            "model": settings.OLLAMA_LLM_MODEL,
            "context_length": settings.LLM_CONTEXT_LENGTH,
            "temperature": settings.LLM_TEMPERATURE,
            "max_output_tokens": settings.LLM_MAX_OUTPUT_TOKENS,
            "timeout_seconds": settings.OLLAMA_TIMEOUT_SECONDS,
            "is_ready": any(settings.OLLAMA_LLM_MODEL in m.get("name", "") for m in installed_models)
        },
        "embedding_model": {
            "model": settings.OLLAMA_EMBED_MODEL,
            "dimensions": 768,
            "is_ready": any(settings.OLLAMA_EMBED_MODEL in m.get("name", "") for m in installed_models)
        }
    }

