def _calculate_dir_size_bytes(dir_path: Path) -> int:
    """Calculates real byte size of directory on disk."""
    total = 0
    if dir_path.exists():
        for entry in os.scandir(dir_path):
            if entry.is_file():
                try:
                    total += entry.stat().st_size
                except OSError:
                    pass
            elif entry.is_dir():
                total += _calculate_dir_size_bytes(Path(entry.path))
    return total

