@router.post("/diagnostics")
def run_full_system_diagnostics(db: Session = Depends(get_db)):
    """
    Executes a comprehensive, itemized diagnostic check of all platform subsystems:
    1. System RAM & OS constraints
    2. SQLite database integrity
    3. ChromaDB collection accessibility
    4. PDF Storage directory & permissions
    5. Ollama Server connectivity
    6. LLM readiness
    7. Embedding readiness
    """
    checks = []

    # 1. System RAM
    mem = psutil.virtual_memory()
    ram_pct = mem.percent
    ram_status = "pass" if ram_pct < 85.0 else ("warn" if ram_pct < 95.0 else "fail")
    checks.append({
        "component": "System RAM & OS",
        "status": ram_status,
        "message": f"RAM usage at {ram_pct:.1f}% ({round(mem.used / 1024**2, 1)} MB / {round(mem.total / 1024**2, 1)} MB). 8 GB Low-RAM mode active.",
        "details": {"used_mb": round(mem.used / 1024**2, 1), "total_mb": round(mem.total / 1024**2, 1), "percent": ram_pct}
    })

    # 2. SQLite Database
    t0 = time.time()
    try:
        with engine.connect() as conn:
            ver = conn.execute(text("SELECT sqlite_version();")).scalar()
            papers_count = conn.execute(text("SELECT COUNT(*) FROM research_papers;")).scalar()
        sq_ms = round((time.time() - t0) * 1000, 2)
        checks.append({
            "component": "SQLite Database",
            "status": "pass",
            "message": f"SQLite v{ver} operational (WAL mode). {papers_count} papers indexed ({sq_ms} ms).",
            "details": {"version": ver, "papers": papers_count, "latency_ms": sq_ms}
        })
    except Exception as e:
        checks.append({
            "component": "SQLite Database",
            "status": "fail",
            "message": f"SQLite connection failed: {str(e)}",
            "details": {"error": str(e)}
        })

    # 3. ChromaDB Vector Store
    t0 = time.time()
    try:
        cs = ChromaService()
        chunks = cs.collection.count()
        ch_ms = round((time.time() - t0) * 1000, 2)
        checks.append({
            "component": "ChromaDB Vector Store",
            "status": "pass",
            "message": f"Collection '{cs.collection_name}' active with {chunks} indexed chunks ({ch_ms} ms).",
            "details": {"collection": cs.collection_name, "chunks": chunks, "latency_ms": ch_ms}
        })
    except Exception as e:
        checks.append({
            "component": "ChromaDB Vector Store",
            "status": "fail",
            "message": f"ChromaDB access failed: {str(e)}",
            "details": {"error": str(e)}
        })

    # 4. PDF Storage
    pdf_dir = Path(settings.PDF_STORAGE_DIR)
    if pdf_dir.exists() and os.access(pdf_dir, os.W_OK):
        files = [f for f in os.listdir(pdf_dir) if f.lower().endswith(".pdf")]
        checks.append({
            "component": "PDF Storage Directory",
            "status": "pass",
            "message": f"Directory accessible and writable. {len(files)} PDFs in repository.",
            "details": {"path": str(pdf_dir), "pdf_count": len(files)}
        })
    else:
        checks.append({
            "component": "PDF Storage Directory",
            "status": "fail",
            "message": f"PDF directory not accessible or read-only: {str(pdf_dir)}",
            "details": {"path": str(pdf_dir)}
        })

    # 5. Ollama Connectivity
    t0 = time.time()
    ollama_stat = ollama_service.get_connection_status_sync()
    ol_ms = round((time.time() - t0) * 1000, 2)
    if ollama_stat.get("connected"):
        checks.append({
            "component": "Ollama Server",
            "status": "pass",
            "message": f"Connected to {settings.OLLAMA_BASE_URL} ({ol_ms} ms). {ollama_stat.get('installed_models_count', 0)} models installed.",
            "details": {"base_url": settings.OLLAMA_BASE_URL, "latency_ms": ol_ms}
        })
    else:
        checks.append({
            "component": "Ollama Server",
            "status": "warn",
            "message": f"Ollama not connected at {settings.OLLAMA_BASE_URL}: {ollama_stat.get('error', 'Service offline')}",
            "details": {"error": ollama_stat.get("error")}
        })

    # 6. Selected LLM Readiness
    is_llm_ready = ollama_stat.get("primary_llm", {}).get("installed", False)
    checks.append({
        "component": f"Selected LLM ({settings.OLLAMA_LLM_MODEL})",
        "status": "pass" if is_llm_ready else "warn",
        "message": f"Target model '{settings.OLLAMA_LLM_MODEL}' is ready for inference." if is_llm_ready else f"Model '{settings.OLLAMA_LLM_MODEL}' not installed in local Ollama repository.",
        "details": {"model": settings.OLLAMA_LLM_MODEL, "installed": is_llm_ready}
    })

    # 7. Embedding Model Readiness
    is_embed_ready = ollama_stat.get("embedding_model", {}).get("installed", False)
    checks.append({
        "component": f"Embedding Model ({settings.OLLAMA_EMBED_MODEL})",
        "status": "pass" if is_embed_ready else "warn",
        "message": f"Embedding model '{settings.OLLAMA_EMBED_MODEL}' is ready (768 dimensions)." if is_embed_ready else f"Embedding model '{settings.OLLAMA_EMBED_MODEL}' not installed in Ollama.",
        "details": {"model": settings.OLLAMA_EMBED_MODEL, "installed": is_embed_ready}
    })

    has_fail = any(c["status"] == "fail" for c in checks)
    has_warn = any(c["status"] == "warn" for c in checks)
    overall = "fail" if has_fail else ("warning" if has_warn else "healthy")

    return {
        "overall_status": overall,
        "timestamp": time.time(),
        "total_checks": len(checks),
        "passed": sum(1 for c in checks if c["status"] == "pass"),
        "warnings": sum(1 for c in checks if c["status"] == "warn"),
        "failures": sum(1 for c in checks if c["status"] == "fail"),
        "checks": checks
    }

