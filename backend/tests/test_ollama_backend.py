import asyncio
import sys
from pathlib import Path
import httpx

# Set up module path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from backend.app.core.config import settings
from backend.app.core.database import init_db, check_db_health
from backend.app.services.ollama_service import ollama_service
from backend.app.main import app

async def run_integration_tests():
    print("=" * 65)
    print("  LITERATURE INTELLIGENCE PLATFORM - LOCAL AI VERIFICATION")
    print("=" * 65)

    # 1. Database Initialization & Health Check
    print("\n[1/6] Testing SQLite Database Initialization...")
    init_db()
    db_status = check_db_health()
    print(f"  -> SQLite Connected: {db_status['connected']}")
    print(f"  -> SQLite Version:   {db_status.get('sqlite_version')}")
    print(f"  -> Database Path:    {db_status.get('database_path')}")
    assert db_status['connected'], "Database connection failed"

    # 2. Ollama Connection & Model Check
    print("\n[2/6] Testing Live Ollama Connection...")
    status = await ollama_service.get_connection_status()
    print(f"  -> Ollama URL:        {status.get('base_url')}")
    print(f"  -> Connected:         {status.get('connected')}")
    print(f"  -> Installed Models:  {status.get('installed_models')}")
    print(f"  -> Target LLM:        {status.get('primary_llm')}")
    print(f"  -> Target Embeddings: {status.get('embedding_model')}")
    assert status.get("connected"), f"Ollama not connected: {status.get('error')}"
    assert status["primary_llm"]["installed"], "qwen3:1.7b is not installed"
    assert status["embedding_model"]["installed"], "nomic-embed-text is not installed"

    # 3. Direct Generation with qwen3:1.7b
    print("\n[3/6] Testing Live Generation with qwen3:1.7b...")
    test_prompt = "What is a literature review in scientific research? Answer in one sentence."
    gen_result = await ollama_service.generate_text(prompt=test_prompt, override_max_tokens=512)
    print(f"  -> Model Used:   {gen_result.get('model')}")
    print(f"  -> Duration:     {gen_result.get('total_duration_ms')} ms")
    print(f"  -> Tokens Eval:  {gen_result.get('eval_count')}")
    print(f"  -> Final Output:\n     \"{gen_result.get('response')}\"")
    assert len(gen_result.get("response", "")) > 0, "No text generated by qwen3:1.7b"

    # 4. Direct Embeddings with nomic-embed-text
    print("\n[4/6] Testing Live Embeddings with nomic-embed-text...")
    test_texts = [
        "Literature Intelligence Platform semantic search test.",
        "Deep learning and transformer architectures for research synthesis."
    ]
    embeddings = await ollama_service.get_embeddings(test_texts)
    print(f"  -> Embeddings count: {len(embeddings)}")
    print(f"  -> Vector dimension: {len(embeddings[0]) if embeddings else 0}")
    print(f"  -> Preview of first 4 values: {embeddings[0][:4]}")
    assert len(embeddings) == 2, "Expected 2 embedding vectors"
    assert len(embeddings[0]) == 768, f"Expected 768 dimensions for nomic-embed-text, got {len(embeddings[0])}"

    # 5. Serialization Lock Check
    print("\n[5/6] Testing Generation Serialization Lock...")
    async def simultaneous_request(idx: int):
        print(f"     [Req {idx}] Queuing generation request...")
        res = await ollama_service.generate_text(prompt="Say hi.", override_max_tokens=200)
        print(f"     [Req {idx}] Completed: '{res.get('response')[:50]}...'")
        return res

    results = await asyncio.gather(simultaneous_request(1), simultaneous_request(2))
    assert len(results) == 2, "Failed concurrent serialization test"

    # 6. Test FastAPI HTTP Endpoints
    print("\n[6/6] Testing FastAPI Endpoints (/api/health, /api/ollama/*)...")
    transport = httpx.ASGITransport(app=app)
    async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
        # GET /api/health
        res_health = await client.get("/api/health")
        print(f"  -> GET /api/health: {res_health.status_code}")
        health_data = res_health.json()
        print(f"     Status: {health_data.get('status')}")
        print(f"     RAM:    {health_data.get('system_resources', {}).get('ram_used_mb')} MB / {health_data.get('system_resources', {}).get('ram_total_mb')} MB ({health_data.get('system_resources', {}).get('ram_percent')}%)")
        assert res_health.status_code == 200, "Health endpoint failed"

        # GET /api/ollama/status
        res_status = await client.get("/api/ollama/status")
        print(f"  -> GET /api/ollama/status: {res_status.status_code}")
        assert res_status.status_code == 200, "Ollama status endpoint failed"

        # GET /api/ollama/models
        res_models = await client.get("/api/ollama/models")
        print(f"  -> GET /api/ollama/models: {res_models.status_code}")
        models_data = res_models.json()
        print(f"     Installed Models Count: {models_data.get('count')}")
        assert res_models.status_code == 200, "Ollama models endpoint failed"

        # POST /api/ollama/test
        print("  -> POST /api/ollama/test (invoking live generation & embedding via API)...")
        res_test = await client.post("/api/ollama/test", json={
            "prompt": "What is scientific hypothesis testing? One sentence.",
            "test_embedding": True
        })
        print(f"  -> POST /api/ollama/test: {res_test.status_code}")
        test_payload = res_test.json()
        print(f"     Status: {test_payload.get('status')}")
        print(f"     LLM Latency: {test_payload.get('llm_test', {}).get('latency_ms')} ms")
        print(f"     LLM Answer: \"{test_payload.get('llm_test', {}).get('response')}\"")
        print(f"     Embed Dimension: {test_payload.get('embedding_test', {}).get('dimension')}")
        assert res_test.status_code == 200, "Ollama test endpoint failed"

    print("\n" + "=" * 65)
    print("  SUCCESS: ALL LOCAL AI BACKEND FOUNDATION TESTS PASSED!")
    print("=" * 65)
    return True

if __name__ == "__main__":
    success = asyncio.run(run_integration_tests())
    sys.exit(0 if success else 1)
